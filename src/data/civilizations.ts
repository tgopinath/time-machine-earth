export const CIV_BY_ID = new Map(CIVILIZATIONS.map((c) => [c.id, c]))

export function civsAt(y: number): Civilization[] {
  return CIVILIZATIONS.filter((c) => y >= c.start && y <= c.end)
}

/** Which curated entity (if any) a dataset feature represents at snapshot year y. */
export function civForFeature(name: string, subjectTo: string | null, y: number): Civilization | null {
  for (const c of CIVILIZATIONS) {
    if (y < c.start || y > c.end) continue
    if (c.matchNames.includes(name)) return c
  }
  if (subjectTo) {
    for (const c of CIVILIZATIONS) {
      if (y < c.start || y > c.end) continue
      if (c.matchSubjects?.includes(subjectTo)) return c
    }
  }
  return null
}

